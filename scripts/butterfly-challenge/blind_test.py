#!/usr/bin/env python3
"""Blind "which butterfly is real?" test for GPT-6-Astra and Claude Fable 5.2 (蝴蝶挑战：和 AI 比一比).

  blind_test.py pairs              photos/<slot>.jpg + ai/<AI_PREFIX>NN.png -> pairs/<NN>-A.jpg, <NN>-B.jpg, answers.json
  blind_test.py run fable|astra    one pass per pair -> experiment/<model>.json (+ raw transcripts)
  blind_test.py retest fable|astra <outdir> <n> [n ...]   only those pairs -> <outdir>/<model>.json
  blind_test.py score              print the table from experiment/*.json

No context for either model: a temp cwd, a clean environment, no tools, no search, no project or user instructions.
  Fable: claude -p --safe-mode --tools '' with a neutral system prompt; images go in as stream-json content blocks.
  Astra: codex exec -m gpt-6-astra --ephemeral -s read-only with a throwaway CODEX_HOME that holds only auth.json
         (so ~/.codex/AGENTS.md and config.toml never load), web search off, and told to run no commands.
Both pictures are cut to 16:9, resized to 1600x900 and re-saved as JPEG q90 without metadata, so file size,
resolution or EXIF cannot give the answer away. Which side is real comes from a fixed seed (5 A, 5 B).
"""
import base64, json, os, random, shutil, subprocess, sys, tempfile, time

DATA = "/Users/yqin/repo/playground/lucas-academy-video-data/butterfly-challenge"
KEYS = ["g1-greta-oto-commons", "p08-2901459", "p15-5129671", "p16-5241558", "p17-7855586",
        "p18-8450772", "p26-16001770", "p44-38657643", "p67-36683557", "p69-37672883"]
# Rounds 1-5 said "One of them is a frame from a real video."; from round 6 the real side is a photograph.
PROMPT = ("Here are two pictures of a butterfly: picture A (the first image) and picture B (the second image). "
          "One of them is a real photograph. The other one was generated by AI. "
          "Look only at the pictures. Do not search, do not use any tools, do not run any commands. "
          "Which picture is the real one? Reply on the first line with only the letter A or B, "
          "then one short sentence on what made you decide.")
TIMEOUT = 600
AI_PREFIX = "v"  # round 4 t, round 5 u, round 6 v (the film), round 7 w (codex_scene.py, retired: 8/10 · 8/10)
# ~/.local/bin/claude is 2.1.261, too old for claude-fable-5-2; the desktop app ships a newer Claude Code.
CLAUDE = os.environ.get("CLAUDE_BIN") or os.path.expanduser(
    "~/Library/Application Support/Claude/claude-code/2.1.321/e6736b2d954d/claude.app/Contents/MacOS/claude")


def norm(src, dst):
    from PIL import Image
    im = Image.open(src).convert("RGB")
    w, h = im.size
    tw, th = (w, round(w * 9 / 16)) if w * 9 / 16 <= h else (round(h * 16 / 9), h)
    left, top = (w - tw) // 2, (h - th) // 2
    im = im.crop((left, top, left + tw, top + th)).resize((1600, 900), Image.LANCZOS)
    im.save(dst, "JPEG", quality=90)  # PIL writes no EXIF unless asked


def pairs():
    """Round 3 (2026-11-11): each real frame (same order as the script) gets a randomly assigned AI picture
    ai/sNN.png from codex_realistic.py (real common species, amateur-video look, passed through H.264).
    Round 1 paired each real frame with a Codex copy of itself; round 2 used made-up species (ai/rNN.png, seed
    20261112). Their pairs, answers and results are in _retired/round1-lookalike-… and _retired/round2-madeup-…."""
    os.makedirs(f"{DATA}/pairs", exist_ok=True)
    # Round 4: ai/tNN.png from codex_macro.py (round 3's species, macro + vivid look). Same seed as round 3, so each
    # real frame keeps round 3's species partner and side; round 3's amateur-look sNN set is in _retired/round3-….
    # Round 6: real side = iNaturalist photos photos/<slot>.jpg (inat_photos.py); AI side = ai/vNN.png (codex_hdphoto.py,
    # round 4's species and scenes as HD photos, 4 with wing motion blur). Same seed, so pairing and sides are unchanged.
    # Rounds 1-5 used video frames real/<key>.png; their pairs and results are in _retired/.
    # Round 7: AI side = ai/wNN.png (codex_scene.py, each AI picture given its real partner's setting, light and size).
    answers = []
    for a in assignment():
        fake_side = "B" if a["real"] == "A" else "A"
        norm(f"{DATA}/photos/{a['key'].split('-')[0]}.jpg", f"{DATA}/pairs/{a['n']:02d}-{a['real']}.jpg")
        norm(f"{DATA}/ai/{AI_PREFIX}{a['slot']}.png", f"{DATA}/pairs/{a['n']:02d}-{fake_side}.jpg")
        answers.append({"n": a["n"], "key": a["key"], "ai": AI_PREFIX + a["slot"], "real": a["real"]})
    json.dump(answers, open(f"{DATA}/pairs/answers.json", "w"), indent=1)
    print("".join(a["real"] for a in answers))


def assignment():
    """Pair n (script order) -> real key, AI slot number ("01".."10") and the side the real picture goes on.
    Fixed seed since round 3, so every round pairs the same real butterfly with the same AI species and side."""
    rng = random.Random(20261113)
    slots = [f"{i:02d}" for i in range(1, 11)]
    rng.shuffle(slots)
    sides = ["A"] * 5 + ["B"] * 5
    rng.shuffle(sides)
    return [dict(n=i, key=k, slot=sl, real=sd) for i, (k, sl, sd) in enumerate(zip(KEYS, slots, sides), 1)]


def clean_env(extra=None):
    env = {"HOME": os.environ["HOME"], "PATH": os.environ["PATH"], "LANG": "en_US.UTF-8", "USER": os.environ.get("USER", "")}
    env.update(extra or {})
    return env


def b64(p):
    return base64.b64encode(open(p, "rb").read()).decode()


def ask_fable(n):
    a, b = f"{DATA}/pairs/{n:02d}-A.jpg", f"{DATA}/pairs/{n:02d}-B.jpg"
    msg = {"type": "user", "message": {"role": "user", "content": [
        {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg", "data": b64(a)}},
        {"type": "image", "source": {"type": "base64", "media_type": "image/jpeg", "data": b64(b)}},
        {"type": "text", "text": PROMPT}]}}
    cmd = [CLAUDE, "-p", "--model", "claude-fable-5-2", "--safe-mode", "--tools", "", "--max-turns", "1",
           "--no-session-persistence", "--system-prompt", "You are a helpful assistant.",
           "--input-format", "stream-json", "--output-format", "stream-json", "--verbose"]
    with tempfile.TemporaryDirectory() as cwd:
        t0 = time.time()
        p = subprocess.run(cmd, input=json.dumps(msg) + "\n", capture_output=True, text=True, cwd=cwd, timeout=TIMEOUT,
                           env=clean_env({"CLAUDE_CODE_DISABLE_ADVISOR_TOOL": "1"}))
    events = [json.loads(l) for l in p.stdout.splitlines() if l.strip().startswith("{")]
    res = next((e for e in events if e.get("type") == "result"), {})
    return {"text": (res.get("result") or "").strip(), "seconds": round(time.time() - t0, 1), "exit": p.returncode,
            "stderr": p.stderr[-500:], "raw": events}


def ask_astra(n):
    a, b = f"{DATA}/pairs/{n:02d}-A.jpg", f"{DATA}/pairs/{n:02d}-B.jpg"
    with tempfile.TemporaryDirectory() as cwd, tempfile.TemporaryDirectory() as home:
        os.symlink(os.path.expanduser("~/.codex/auth.json"), f"{home}/auth.json")
        shutil.copy(a, f"{cwd}/A.jpg"); shutil.copy(b, f"{cwd}/B.jpg")
        cmd = ["codex", "exec", "--skip-git-repo-check", "--ephemeral", "--ignore-user-config", "-s", "read-only",
               "-C", cwd, "-m", "gpt-6-astra", "-c", 'web_search="disabled"', "--json",
               PROMPT, "-i", f"{cwd}/A.jpg", "-i", f"{cwd}/B.jpg"]  # -i takes several values, so the prompt goes first
        t0 = time.time()
        p = subprocess.run(cmd, stdin=subprocess.DEVNULL, capture_output=True, text=True, cwd=cwd, timeout=TIMEOUT,
                           env=clean_env({"CODEX_HOME": home}))
    events = [json.loads(l) for l in p.stdout.splitlines() if l.strip().startswith("{")]
    texts, tools = [], []
    for e in events:
        item = e.get("item") or {}
        if item.get("type") == "agent_message":
            texts.append(item.get("text", ""))
        elif item and item.get("type") not in ("reasoning", "agent_message"):
            tools.append(item.get("type"))
    return {"text": (texts[-1] if texts else "").strip(), "seconds": round(time.time() - t0, 1), "exit": p.returncode,
            "tool_items": tools, "stderr": p.stderr[-500:], "raw": events}


def guess(text):
    first = text.strip().splitlines()[0].strip().strip("*").strip() if text.strip() else ""
    return first[:1].upper() if first[:1].upper() in ("A", "B") else "?"


def run(which, only=None, outdir="experiment"):
    """One pass per pair. With `only` (pair numbers) it asks just those pairs and writes to `outdir`, so a retest
    never overwrites the round's full results. Every pair is its own fresh process either way: nothing carries over
    from one pair to the next, or from the earlier run."""
    ask = {"fable": ask_fable, "astra": ask_astra}[which]
    answers = [a for a in json.load(open(f"{DATA}/pairs/answers.json")) if not only or a["n"] in only]
    os.makedirs(f"{DATA}/{outdir}/raw", exist_ok=True)
    out = []
    for a in answers:
        r = ask(a["n"])
        g = guess(r["text"])
        json.dump(r, open(f"{DATA}/{outdir}/raw/{which}-{a['n']:02d}.json", "w"), ensure_ascii=False, indent=1)
        row = {"n": a["n"], "key": a["key"], "ai": a.get("ai"), "real": a["real"], "guess": g, "correct": g == a["real"],
               "reply": r["text"], "seconds": r["seconds"], "exit": r["exit"]}
        if which == "astra":
            row["tool_items"] = r["tool_items"]
        out.append(row)
        print(which, a["n"], "real", a["real"], "guess", g, "OK" if g == a["real"] else "--", r["seconds"], "s", flush=True)
    json.dump(out, open(f"{DATA}/{outdir}/{which}.json", "w"), ensure_ascii=False, indent=1)
    print(which, "score", sum(r["correct"] for r in out), "/", len(out))


def score():
    for which in ("astra", "fable"):
        p = f"{DATA}/experiment/{which}.json"
        if os.path.exists(p):
            rows = json.load(open(p))
            print(which, sum(r["correct"] for r in rows), "/", len(rows), " ".join(("✓" if r["correct"] else "✗") for r in rows))


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "pairs":
        pairs()
    elif cmd == "run" and len(sys.argv) > 2:
        run(sys.argv[2])
    elif cmd == "retest" and len(sys.argv) > 4:  # retest <model> <outdir> <n> [n ...]
        run(sys.argv[2], {int(x) for x in sys.argv[4:]}, sys.argv[3])
    elif cmd == "score":
        score()
    else:
        sys.exit(__doc__)
