def prompt_for(key):
    medium, role, about, scenes = PIECES[key]
    star = CAMEO if role == "cameo" else STAR_MAIN
    lines = [f"{i + 1}. 输出到 pictures/m{key}-{n:02d}.png：{s}" for i, (n, s) in enumerate(scenes)]
    return (PRE.replace("{key}", key) + f"这一组画的是：{about}\n画法（每一张都一样）：{STYLE[medium]}\n{star}\n{COMMON}\n"
            "同一组里同一个角色每一张都要长得一样（先画第 1 张，后面的都参考第 1 张里的角色）。\n\n" + "\n\n".join(lines))


def run(key):
    tag = f"scenes-{key}"
    os.makedirs(f"{DATA}/codex-runs", exist_ok=True)
    prompt = prompt_for(key)
    open(f"{DATA}/codex-runs/{tag}.prompt.md", "w").write(prompt)
    cmd = ["codex", "exec", "--skip-git-repo-check", "-s", "workspace-write", "-C", DATA, "--enable", "image_generation",
           "-c", 'model_reasoning_effort="medium"', "-o", f"{DATA}/codex-runs/{tag}.last.md", "-i", STAR_REF, "-"]
    with open(f"{DATA}/codex-runs/{tag}.log", "w") as log:
        r = subprocess.run(cmd, input=prompt, text=True, stdout=log, stderr=subprocess.STDOUT)
    made = [n for n, _ in PIECES[key][3] if os.path.exists(f"{DATA}/pictures/m{key}-{n:02d}.png")]
    print(f"{key}: exit {r.returncode}, {len(made)}/{len(PIECES[key][3])} pictures", flush=True)


def main():
    keys = list(PIECES) if sys.argv[1] == "all" else sys.argv[1:]
    with ThreadPoolExecutor(max_workers=4) as ex: list(ex.map(run, keys))


if __name__ == "__main__":
    main()
